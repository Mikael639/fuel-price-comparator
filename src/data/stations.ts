import type {
  FuelPrices,
  FuelStation,
  FuelType,
  PriceHistory,
  ServiceType,
} from "@/types/station";

const HISTORY_DATES = [
  "2026-03-05",
  "2026-03-06",
  "2026-03-07",
  "2026-03-08",
  "2026-03-09",
  "2026-03-10",
  "2026-03-11",
];

const createHistorySeries = (values: number[]) =>
  values.map((price, index) => ({
    date: HISTORY_DATES[index],
    price,
  }));

const services = (...items: ServiceType[]) => items;

const createStation = (
  station: Omit<FuelStation, "fuels" | "priceHistory" | "brandSource"> & {
    fuelPrices: FuelPrices;
    history: Partial<Record<FuelType, number[]>>;
  },
): FuelStation => {
  const priceHistory = Object.entries(station.history).reduce<PriceHistory>(
    (history, [fuel, values]) => {
      history[fuel as FuelType] = createHistorySeries(values as number[]);
      return history;
    },
    {},
  );

  return {
    id: station.id,
    name: station.name,
    brand: station.brand,
    brandSource: "mock",
    address: station.address,
    city: station.city,
    lat: station.lat,
    lng: station.lng,
    isOpen: station.isOpen,
    openingHours: station.openingHours,
    fuelPrices: station.fuelPrices,
    fuels: Object.keys(station.fuelPrices) as FuelType[],
    priceHistory,
    services: station.services,
  };
};

